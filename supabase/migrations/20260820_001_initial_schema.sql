alter table public.barbers enable row level security;
alter table public.barber_users enable row level security;
alter table public.barber_services enable row level security;
alter table public.availability_overrides enable row level security;
alter table public.reservations enable row level security;

create policy "public can read barbers"
on public.barbers for select
to anon, authenticated
using (true);

create policy "public can read enabled services"
on public.barber_services for select
to anon, authenticated
using (enabled or exists (
  select 1 from public.barber_users bu
  where bu.user_id = auth.uid() and bu.barber_id = barber_services.barber_id
));

create policy "barbers can update own services"
on public.barber_services for update
to authenticated
using (exists (
  select 1 from public.barber_users bu
  where bu.user_id = auth.uid() and bu.barber_id = barber_services.barber_id
))
with check (exists (
  select 1 from public.barber_users bu
  where bu.user_id = auth.uid() and bu.barber_id = barber_services.barber_id
));

create policy "barbers can read own account"
on public.barber_users for select
to authenticated
using (user_id = auth.uid());

create policy "public can read availability"
on public.availability_overrides for select
to anon, authenticated
using (true);

create policy "barbers manage own availability"
on public.availability_overrides for all
to authenticated
using (exists (
  select 1 from public.barber_users bu
  where bu.user_id = auth.uid() and bu.barber_id = availability_overrides.barber_id
))
with check (exists (
  select 1 from public.barber_users bu
  where bu.user_id = auth.uid() and bu.barber_id = availability_overrides.barber_id
));

create policy "barbers read own reservations"
on public.reservations for select
to authenticated
using (exists (
  select 1 from public.barber_users bu
  where bu.user_id = auth.uid() and bu.barber_id = reservations.barber_id
));

create policy "barbers update own reservations"
on public.reservations for update
