create extension if not exists pgcrypto;

create table public.barbers (
  id text primary key,
  name text not null,
  created_at timestamptz not null default now()
);

create table public.barber_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  barber_id text not null references public.barbers(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.barber_services (
  id bigint generated by default as identity primary key,
  barber_id text not null references public.barbers(id) on delete cascade,
  code text not null,
  name text not null,
  duration_minutes integer not null check (duration_minutes > 0),
  price_cents integer not null check (price_cents >= 0),
  enabled boolean not null default true,
  unique (barber_id, code)
);

create table public.availability_overrides (
  id bigint generated by default as identity primary key,
  barber_id text not null references public.barbers(id) on delete cascade,
  appointment_date date not null,
  appointment_time time not null,
  enabled boolean not null,
  created_at timestamptz not null default now(),
  unique (barber_id, appointment_date, appointment_time)
);

create table public.reservations (
  id bigint generated by default as identity primary key,
  barber_id text not null references public.barbers(id) on delete restrict,
  appointment_date date not null,
  appointment_time time not null,
  service_code text,
  service_name text,
  service_duration integer,
  price_cents integer,
  customer_name text not null,
  customer_phone text not null,
  customer_email text not null,
  management_token_hash text unique,
  status text not null default 'confirmed' check (status in ('confirmed', 'cancelled')),
  created_at timestamptz not null default now(),
  unique (barber_id, appointment_date, appointment_time)
);

create index reservations_barber_date_idx
  on public.reservations (barber_id, appointment_date);

